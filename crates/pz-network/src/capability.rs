#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ordinals_follow_declaration_order() {
        for (i, c) in Capability::ALL.iter().enumerate() {
            assert_eq!(c.ordinal(), i);
            assert_eq!(Capability::from_ordinal(i), Some(*c));
            assert_eq!(Capability::from_name(c.name()), Some(*c));
        }
        assert_eq!(Capability::None.ordinal(), 0);
        assert_eq!(Capability::LoginOnServer.ordinal(), 1);
        assert_eq!(Capability::from_name("NoSuchCapability"), None);
    }
}
