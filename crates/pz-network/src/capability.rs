    /// `Capability.valueOf(name)`; `None` where Java throws.
    pub fn from_name(name: &str) -> Option<Capability> {
        Capability::ALL.iter().copied().find(|c| c.name() == name)
    }

    /// `Capability.values()[ordinal]`.
    pub fn from_ordinal(ordinal: usize) -> Option<Capability> {
        Capability::ALL.get(ordinal).copied()
    }
